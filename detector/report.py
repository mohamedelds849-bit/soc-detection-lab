#!/usr/bin/env python3
"""Console + HTML triage report rendering for detector alerts."""
from __future__ import annotations

import html
from collections import Counter

SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
SEV_COLOR = {"critical": "#b00020", "high": "#d9534f", "medium": "#e0a800",
             "low": "#5bc0de", "info": "#777"}


def console_report(alerts, total_events: int) -> str:
    lines = []
    lines.append("=" * 72)
    lines.append("SOC DETECTION LAB  --  OFFLINE DETECTION RUN")
    lines.append("=" * 72)
    lines.append(f"Events analyzed : {total_events}")
    lines.append(f"Alerts raised   : {len(alerts)}")
    by_sev = Counter(a.severity for a in alerts)
    sev_line = "  ".join(f"{s}={by_sev.get(s,0)}" for s in ["critical", "high", "medium", "low"])
    lines.append(f"By severity     : {sev_line}")
    lines.append("-" * 72)
    for a in sorted(alerts, key=lambda x: (SEV_ORDER.get(x.severity, 9), x.ts)):
        lines.append(f"[{a.severity.upper():8}] {a.time_str}  {a.name}")
        lines.append(f"           ATT&CK {a.attack} | source={a.source} | entity={a.entity} | hits={a.count}")
        if a.triage:
            lines.append(f"           triage: {' '.join(a.triage.split())}")
        for ev in a.evidence[:3]:
            lines.append(f"             - {str(ev)[:110]}")
        lines.append("")
    return "\n".join(lines)


def html_report(alerts, total_events: int) -> str:
    by_sev = Counter(a.severity for a in alerts)
    rows = []
    for a in sorted(alerts, key=lambda x: (SEV_ORDER.get(x.severity, 9), x.ts)):
        color = SEV_COLOR.get(a.severity, "#777")
        ev_html = "<br>".join(html.escape(str(e)[:160]) for e in a.evidence[:4])
        rows.append(f"""
        <tr>
          <td><span class="sev" style="background:{color}">{html.escape(a.severity.upper())}</span></td>
          <td>{html.escape(a.time_str)}</td>
          <td><b>{html.escape(a.name)}</b><div class="triage">{html.escape(' '.join(a.triage.split()))}</div></td>
          <td><code>{html.escape(a.attack)}</code></td>
          <td>{html.escape(a.source)}</td>
          <td>{html.escape(a.entity)}</td>
          <td class="num">{a.count}</td>
          <td class="ev">{ev_html}</td>
        </tr>""")

    cards = "".join(
        f'<div class="card" style="border-color:{SEV_COLOR[s]}"><div class="n">{by_sev.get(s,0)}</div>'
        f'<div class="l">{s}</div></div>'
        for s in ["critical", "high", "medium", "low"])

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>SOC Detection Lab - Triage Report</title>
<style>
  body {{ font-family: system-ui, Segoe UI, Arial, sans-serif; margin: 0; background:#0f1115; color:#e6e6e6; }}
  header {{ padding: 24px; background:#171a21; border-bottom:1px solid #2a2f3a; }}
  h1 {{ margin:0 0 4px; font-size:20px; }}
  .sub {{ color:#9aa4b2; font-size:13px; }}
  .cards {{ display:flex; gap:12px; padding:18px 24px; flex-wrap:wrap; }}
  .card {{ background:#171a21; border-left:4px solid; border-radius:8px; padding:12px 18px; min-width:90px; }}
  .card .n {{ font-size:26px; font-weight:700; }}
  .card .l {{ font-size:12px; text-transform:uppercase; color:#9aa4b2; }}
  table {{ border-collapse:collapse; width:calc(100% - 48px); margin:0 24px 40px; font-size:13px; }}
  th, td {{ text-align:left; padding:10px; border-bottom:1px solid #242a35; vertical-align:top; }}
  th {{ color:#9aa4b2; text-transform:uppercase; font-size:11px; letter-spacing:.04em; }}
  .sev {{ color:#fff; padding:2px 8px; border-radius:10px; font-size:11px; font-weight:700; }}
  .triage {{ color:#9aa4b2; font-size:12px; margin-top:4px; max-width:420px; }}
  .ev {{ font-family: ui-monospace, Consolas, monospace; font-size:11px; color:#c7d0dc; max-width:380px; word-break:break-all; }}
  code {{ background:#242a35; padding:1px 6px; border-radius:4px; }}
  .num {{ text-align:center; }}
  footer {{ padding:16px 24px; color:#6b7280; font-size:12px; }}
</style></head>
<body>
<header>
  <h1>SOC Detection Lab &mdash; Offline Triage Report</h1>
  <div class="sub">{total_events} events analyzed &middot; {len(alerts)} alerts &middot; synthetic lab data (defensive exercise)</div>
</header>
<div class="cards">{cards}</div>
<table>
  <thead><tr><th>Severity</th><th>Time (UTC)</th><th>Detection</th><th>ATT&amp;CK</th>
  <th>Source</th><th>Entity</th><th>Hits</th><th>Evidence (sample)</th></tr></thead>
  <tbody>{''.join(rows)}</tbody>
</table>
<footer>Generated by the offline detection engine. All data is synthetic; IPs use RFC 5737 / RFC 1918 ranges.</footer>
</body></html>"""
